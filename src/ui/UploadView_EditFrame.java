        if (row.get(0).equals(selectedFile)) {
            if (jTextArea1 != null) {
                jTextArea1.setText((String) row.get(1));
            }
//            if (jLabel2 != null) {
//                jLabel2.setText("Uploaded On: " + row.get(2));
//            }
            break;
        }
