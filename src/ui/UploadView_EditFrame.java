    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
      String selectedFile = (String) jComboBox1.getSelectedItem();
    String newDescription = jTextArea1.getText().trim();
    String username = operationsFrame.studentname; // or wherever you store it
    String currentTime = new SimpleDateFormat("yyyy-MM-dd HH:mm:ss").format(new Date());

    UploadOP op = new UploadOP();
    boolean success = op.isUploadInfoEdited(username, selectedFile, newDescription, currentTime);

    if (success) {
        JOptionPane.showMessageDialog(null, "File description updated successfully.");
    } else {
        JOptionPane.showMessageDialog(null, "Failed to update file description.");
    }
    }//GEN-LAST:event_jButton1ActionPerformed

